        /**
         * From the system language: LUKSMUSIC_LANG, then the POSIX variables (read directly, since Java falls back to
         * English when the locale isn't generated, as can happen on SteamOS), then Java's locale.
         */
        fun system(env: (String) -> String? = System::getenv, javaLanguage: String = Locale.getDefault().language): Strings {
            val chosen = listOf("LUKSMUSIC_LANG", "LC_ALL", "LC_MESSAGES", "LANG")
                .firstNotNullOfOrNull { name -> env(name)?.takeIf { it.isNotBlank() && it != "C" && it != "POSIX" && !it.startsWith("C.") } }
            return forLanguage(chosen ?: javaLanguage)
        }
